function scenario(overrides = {}) {
    const actor = named({}, 'actor');
    const creature = named({}, 'creature');
    const other = named({}, 'other');
    const player = named({}, 'player');
    const config = {
        pvpHandoffPending: false, accountId: 'bot_caster',
        pvp: [], participants: [], canUse: true, optionalMissing: false,
        mp: 100, mpCosts: [30, 77], hp: 50, hpCost: 0,
        condition: null, magic: true, castTime: 1000, targetKind: 'enemy', semantic: {},
        targets: null, items: true, raidCurse: false, charges: true,
        outcomes: new Map(), offensive: new Map(), pickup: [], queueName: undefined,
        npcCombatant: false, weaponCalls: 0,
        actor, creature, other, player,
        ...overrides
    };
    return config;
}

function run(config) {
    cfg = config;
    log = [];
    timers = [];
    const { actor, creature, other, player } = config;
    let mp = config.mp, hp = config.hp, casts = false;
    Object.assign(actor, {
        fetchId: () => 1001,
        fetchName: () => 'Caster',
        fetchMp: () => mp,
        setMp(value) { ev('actor.setMp', value); mp = value; },
        fetchHp: () => hp,
        setHp(value) { ev('actor.setHp', value); hp = value; },
        statusUpdateVitals(target) { ev('actor.statusUpdateVitals', target); },
        state: {
            setCasts(value) { ev('actor.setCasts', value); casts = value; },
            fetchCasts: () => casts
        },
        automation: { replenishVitals(target) { ev('automation.replenishVitals', target); } }
    });
    if (!config.optionalMissing) {
        actor.canUseSkill = (skill) => { ev('actor.canUseSkill', skill); return config.canUse; };
        actor.markSkillReuse = (skill) => ev('actor.markSkillReuse', skill);
    }
    let creatureHp = config.creatureHp ?? 40;
    Object.assign(creature, {
        fetchId: () => 3001,
        fetchName: () => 'Creature',
        fetchHp: () => creatureHp,
        setHp(value) { ev('creature.setHp', value); creatureHp = value; },
        setCp(value) { ev('creature.setCp', value); },
        statusUpdateVitals(target) { ev('creature.statusUpdateVitals', target); }
    });
    Object.assign(other, { fetchId: () => 3002, fetchName: () => 'Other', fetchHp: () => 0 });
    const playerSession = named({ accountId: 'player_account', actor: player,
        dataSendToMe(packet) { ev('playerSession.dataSendToMe', packet); } }, 'playerSession');
    Object.assign(player, { fetchId: () => 4001, fetchName: () => 'Player', session: playerSession });

    const skill = named({
        fetchSelfId: () => 1177,
        model: { name: 'Wind Strike' },
        fetchConsumedHp: () => config.hpCost,
        setCalculatedHitTime(value) { ev('skill.setCalculatedHitTime', value); this.calculatedHitTime = value; },
        fetchCalculatedHitTime() { return this.calculatedHitTime; }
    }, 'skill');
    if (!config.optionalMissing) {
        skill.fetchTargetKind = () => config.targetKind;
        skill.fetchSemantic = () => config.semantic;
    }

    const session = named({
        actor,
        accountId: config.accountId,
        pvpHandoffPending: config.pvpHandoffPending,
        dataSendToMe(packet) { ev('session.dataSendToMe', packet); },
        dataSendToMeAndOthers(packet, from) { ev('session.dataSendToMeAndOthers', packet, from); }
    }, 'session');

    const attack = named(new Attack(), 'attack');
    attack.queue.name = config.queueName;
    const targetSequence = config.targets ? config.targets.slice() : null;
    Object.assign(attack, {
        blockedPvpDefense(...args) { ev('blockedPvpDefense', ...args); return next(config.pvp, false); },
        checkParticipants(...args) { ev('checkParticipants', ...args); return next(config.participants, false); },
        skillMpCost(...args) { ev('skillMpCost', ...args); return next(config.mpCosts, 0); },
        skillUseConditionFailure(...args) { ev('skillUseConditionFailure', ...args); return config.condition; },
        rejectSkillUseCondition(...args) { ev('rejectSkillUseCondition', ...args); },
        isMagicSkill(...args) { ev('isMagicSkill', ...args); return config.magic; },
        chargeShotForSkill(...args) { ev('chargeShotForSkill', ...args); },
        calculatedSkillHitTime(...args) { ev('calculatedSkillHitTime', ...args); return config.castTime; },
        resolveSkillTargets(...args) {
            ev('resolveSkillTargets', ...args);
            return targetSequence ? next(targetSequence, []) : [creature];
        },
        consumeSkillItems(...args) { ev('consumeSkillItems', ...args); return config.items; },
        consumeSkillCharges(...args) {
            ev('consumeSkillCharges', ...args);
            if (config.charges) actor.activeSkillChargeCount = 2;
            return config.charges;
        },
        captureShotState(...args) { ev('captureShotState', ...args); return named({}, 'shotState'); },
        restoreShotState(...args) { ev('restoreShotState', ...args); },
        clearLoadedShot(...args) { ev('clearLoadedShot', ...args); },
        recordPlayerAggression(...args) { ev('recordPlayerAggression', ...args); },
        hit(...args) { ev('hit', ...args); },
        isNpcCombatant(...args) { ev('isNpcCombatant', ...args); return config.npcCombatant; },
        dequeueEvent(...args) { ev('dequeueEvent', ...args); }
    });

    const result = attack.remoteHit(session, creature, skill);
    const state = () => 'mp=' + mp + ' hp=' + hp + ' casts=' + casts + ' activeCast=' + label(attack.activeCast)
        + ' charges=' + ('activeSkillChargeCount' in actor ? actor.activeSkillChargeCount : 'none')
        + ' liveTimers=' + attack.timers.size;
    log.push('return ' + label(result) + ' ' + state());
    for (const timer of timers) {
        if (timer.canceled) continue;
        log.push('fire ' + timer.delay);
        const fired = timer.callback();
        log.push('after ' + label(fired) + ' ' + state());
    }
    return log;
}

