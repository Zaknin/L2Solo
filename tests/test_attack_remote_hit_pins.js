function patch(object, key, replacement) {
    saved.push([object, key, object[key]]);
    object[key] = replacement;
}
function recorder(moduleName, key, answer = () => undefined) {
    patch(modules[moduleName], key, (...args) => { ev(moduleName + '.' + key, ...args); return answer(...args); });
}
