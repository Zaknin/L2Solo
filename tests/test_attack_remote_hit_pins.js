function named(value, name) { names.set(value, name); return value; }
function label(value) {
    if (names.has(value)) return names.get(value);
    if (value === undefined) return 'undefined';
    if (Array.isArray(value)) return '[' + value.map(label).join(',') + ']';
    if (typeof value === 'function') return 'fn';
    if (value && typeof value === 'object') {
        return '{' + Object.keys(value).map(key => key + ':' + label(value[key])).join(',') + '}';
    }
    return JSON.stringify(value);
}
function ev(name, ...args) { log.push(name + '(' + args.map(label).join(',') + ')'); }
named(invoke('GameServer/World/World'), 'World');
function next(list, fallback) { return list.length ? list.shift() : fallback; }

