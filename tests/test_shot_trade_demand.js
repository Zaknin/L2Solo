'use strict';
const assert = require('node:assert/strict');
const Demand = require('../src/GameServer/Bot/Economy/ShotTradeDemand');
const now = Date.now();
assert.equal(Demand.forecast(1463, 'Dion', now), null);
assert.equal(Demand.deal(1864, 10000, 'Dion', now), null, 'material buyers do not create shot demand');
Demand.deal(1463, 1000, 'Dion', now - 600000);
assert.equal(Demand.forecast(1463, 'Dion', now), null, 'one sale is insufficient evidence');
Demand.deal(1463, 500, 'Dion', now - 300000);
const native = Demand.forecast(1463, 'Dion', now);
assert(native.applicableUnits > 0 && native.applicableUnits < 750);
assert.equal(native.guaranteed, false); assert.equal(native.repeatable, false);
assert.equal(Demand.forecast(1464, 'Dion', now), null, 'D purchases say nothing about C shots');
assert.equal(Demand.forecast(1463, 'Giran', now), null, 'demand retains the observed town');
assert.equal(Demand.forecast(1463, 'Dion', now + 24 * 3600000), null, 'stale demand decays away');
const rows = new Map(Demand.rows().map(row => [row[0], row]));
Demand.useTable(() => rows);
assert.deepEqual(Demand.forecast(1463, 'Dion', now), native, 'worker mirror preserves native demand exactly');
rows.clear(); assert.equal(Demand.forecast(1463, 'Dion', now), null);
Demand.reset();
console.log('PASS item/town public shot demand, finite forecast, decay, absence and worker parity');
